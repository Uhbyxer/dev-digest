import type { CiPostAs, CiTarget, CiTrigger } from '@devdigest/shared';

/**
 * Generated CI config. Pure template strings (plan R2) — one file, no template
 * engine. Security properties of the GitHub Actions workflow (AC-15..19):
 *  - `on: pull_request` ONLY (no comment events) with the chosen types
 *  - `permissions:` exactly `contents: read` + `pull-requests: write`
 *  - OpenRouter key only via `secrets.OPENROUTER_API_KEY`
 *  - job `if:` withholds the keyed job from fork PRs
 *  - review step runs the bundled `.devdigest/runner/index.js` (no marketplace action)
 */

/** Bumped when the generated template changes; stored on the installation. */
export const WORKFLOW_VERSION = '1';

export const GHA_WORKFLOW_PATH = '.github/workflows/devdigest-review.yml';
export const RUNNER_PATH = '.devdigest/runner/index.js';

/** Where the config file for each target lives. */
export const WORKFLOW_PATHS: Record<CiTarget, string> = {
  gha: GHA_WORKFLOW_PATH,
  circle: '.circleci/config.yml',
  jenkins: 'Jenkinsfile',
  cli: '.devdigest/run-review.sh',
};

export interface BuildWorkflowInput {
  target?: CiTarget;
  triggers: CiTrigger[];
  postAs: CiPostAs;
  /** Validated "owner/name" target repo; a placeholder is used at preview time when absent. */
  repo?: string;
}

export function buildWorkflow(input: BuildWorkflowInput): string {
  switch (input.target ?? 'gha') {
    case 'circle':
      return buildCircle(input.postAs);
    case 'jenkins':
      return buildJenkins(input.postAs, input.repo ?? 'owner/name');
    case 'cli':
      return buildCli(input.postAs);
    default:
      return buildGithubActions(input);
  }
}

function buildGithubActions({ triggers, postAs }: BuildWorkflowInput): string {
  // Triggers/postAs are enum-validated upstream; dedupe + keep stable order anyway.
  const order: CiTrigger[] = ['opened', 'synchronize', 'reopened'];
  const types = order.filter((t) => triggers.includes(t));
  return `# Generated by DevDigest (workflow version ${WORKFLOW_VERSION}). Review this file like code.
name: DevDigest Review

on:
  pull_request:
    types: [${types.join(', ')}]

# Least privilege: read the repo, write PR reviews/comments. Nothing else.
permissions:
  contents: read
  pull-requests: write

jobs:
  review:
    # Fork PRs never get the OpenRouter secret: the keyed job does not run for them.
    if: github.event.pull_request.head.repo.full_name == github.repository
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
        with:
          persist-credentials: false
      - uses: actions/setup-node@v4
        with:
          node-version: 22
      - name: DevDigest review
        run: node ${RUNNER_PATH}
        env:
          OPENROUTER_API_KEY: \${{ secrets.OPENROUTER_API_KEY }}
          GITHUB_TOKEN: \${{ secrets.GITHUB_TOKEN }}
          GITHUB_REPOSITORY: \${{ github.repository }}
          PR_NUMBER: \${{ github.event.pull_request.number }}
          DEVDIGEST_POST_AS: ${postAs}
      - name: Upload result
        if: always()
        uses: actions/upload-artifact@v4
        with:
          name: devdigest-result
          path: devdigest-result.json
          if-no-files-found: ignore
`;
}

// Non-GHA targets are file-download only (Q3). They follow the same principle
// (key from the CI system's secret store, bundled runner) but get no PR
// automation, tracking, or ingest.

function buildCircle(postAs: CiPostAs): string {
  return `# Generated by DevDigest. Add OPENROUTER_API_KEY and GITHUB_TOKEN as CircleCI environment variables.
version: 2.1
jobs:
  devdigest-review:
    docker:
      - image: cimg/node:22.0
    environment:
      DEVDIGEST_POST_AS: ${postAs}
    steps:
      - checkout
      - run:
          name: DevDigest review
          command: |
            export GITHUB_REPOSITORY="$CIRCLE_PROJECT_USERNAME/$CIRCLE_PROJECT_REPONAME"
            export PR_NUMBER="\${CIRCLE_PULL_REQUEST##*/}"
            node ${RUNNER_PATH}
      - store_artifacts:
          path: devdigest-result.json
workflows:
  review:
    jobs:
      - devdigest-review
`;
}

function buildJenkins(postAs: CiPostAs, repo: string): string {
  return `// Generated by DevDigest. Provide credentials OPENROUTER_API_KEY and GITHUB_TOKEN (secret text).
pipeline {
  agent any
  environment {
    OPENROUTER_API_KEY = credentials('OPENROUTER_API_KEY')
    GITHUB_TOKEN = credentials('GITHUB_TOKEN')
    DEVDIGEST_POST_AS = '${postAs}'
    GITHUB_REPOSITORY = '${repo}'
  }
  stages {
    stage('DevDigest review') {
      when { changeRequest() }
      steps {
        sh 'PR_NUMBER="$CHANGE_ID" node ${RUNNER_PATH}'
      }
    }
  }
  post {
    always { archiveArtifacts artifacts: 'devdigest-result.json', allowEmptyArchive: true }
  }
}
`;
}

function buildCli(postAs: CiPostAs): string {
  return `#!/usr/bin/env sh
# Generated by DevDigest. Export OPENROUTER_API_KEY, GITHUB_TOKEN, GITHUB_REPOSITORY (owner/name)
# and PR_NUMBER in your CI environment, then run this script. Never commit secrets.
set -eu
DEVDIGEST_POST_AS=${postAs} exec node ${RUNNER_PATH}
`;
}
